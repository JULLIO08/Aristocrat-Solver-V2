"""Regenerate the README Results section from eval --json output.

Usage: python scripts/update_readme.py results/final_eval.json [results/final_holdout.json]
Rewrites everything between the RESULTS markers in README.md.
"""
import json
import sys
from pathlib import Path

PKG_ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- RESULTS:BEGIN (generated by scripts/update_readme.py - do not edit) -->"
END = "<!-- RESULTS:END -->"


def block_for(payload: dict, title: str) -> str:
    s = payload["summary"]
    cfg = payload["config"]
    lines = [
        f"### {title}",
        "",
        f"`eval --n {cfg['n']} --restarts {cfg['restarts']} --iters "
        f"{cfg['iters']}{' --holdout' if cfg.get('holdout') else ''}` "
        f"(seed {cfg['seed']}):",
        "",
        f"- **Exact-solve rate: {s['exact_solve_rate']:.0%}** "
        f"(95% CI {s['exact_solve_ci95'][0]:.0%}-{s['exact_solve_ci95'][1]:.0%})",
        f"- Mean letter-error rate: **{s['mean_error_rate']:.4f}**",
        f"- Median wall time {s['median_wall_time']:.1f}s, "
        f"p95 {s['p95_wall_time']:.1f}s; {s['escalated']} of {s['n']} escalated",
        "",
        "| Bucket | n | exact-solve | 95% CI | mean err rate |",
        "|---|---|---|---|---|",
    ]
    for name in ("<60", "60-120", ">120"):
        b = s["buckets"][name]
        if not b["n"]:
            continue
        lines.append(
            f"| {name} | {b['n']} | {b['exact_solve_rate']:.0%} "
            f"| {b['ci95'][0]:.0%}-{b['ci95'][1]:.0%} "
            f"| {b['mean_error_rate']:.4f} |")
    return "\n".join(lines)


def main() -> int:
    blocks = []
    titles = ["Standard protocol (seed-123 sample, mostly seen in LM training)",
              "True held-out (never-trained 5% split)"]
    for path, title in zip(sys.argv[1:], titles):
        blocks.append(block_for(json.loads(Path(path).read_text(encoding="utf-8")),
                                title))
    readme = PKG_ROOT / "README.md"
    text = readme.read_text(encoding="utf-8")
    if BEGIN not in text:
        print(f"error: marker not found in {readme}")
        return 1
    head, rest = text.split(BEGIN, 1)
    _, tail = rest.split(END, 1)
    new = head + BEGIN + "\n\n" + "\n\n".join(blocks) + "\n\n" + END + tail
    readme.write_text(new, encoding="utf-8")
    print(f"README Results regenerated from {len(blocks)} JSON file(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
